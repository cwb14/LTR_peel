#!/usr/bin/env python3
"""Write MaskerAide (rmfast) masking jobs: mask/<ds>/<name>/cmd.sh, appended to a jobs.tsv for queue.py.

Parameters are EDTA's documented benchmark settings (EDTA README, 'Benchmark'):
  RepeatMasker -e ncbi -pa 36 -q -no_is -norna -nolow -div 40 -lib LIB -cutoff 225 GENOME
run with rmfast (MaskerAide: RepeatMasker 4.2.4 re-implementation, rmblast engine) and -pa 16.
"""
import argparse
import csv
import os
import sys

B = os.environ["BENCH_ROOT"]
RMFAST = f"{B}/build/MaskerAide/target/release/rmfast"
T = 16


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write rmfast masking jobs (EDTA benchmark parameters).")
    ap.add_argument("--ds", required=True, help="dataset (bench/data/<ds>/genome.fa)")
    ap.add_argument("--lib", required=True, nargs=2, action="append", metavar=("NAME", "FASTA"),
                    help="library name and FASTA (repeatable)")
    ap.add_argument("--jobs", required=True, help="jobs.tsv to append to (created with header if missing)")
    ap.add_argument("--force", action="store_true", help="overwrite existing cmd.sh")
    a = ap.parse_args(argv)
    g = f"{B}/data/{a.ds}/genome.fa"
    if not os.path.exists(g):
        sys.exit(f"error: {g} missing")
    rows = []
    for name, lib in a.lib:
        lib = os.path.abspath(lib)
        if not os.path.exists(lib):
            sys.exit(f"error: library {lib} missing")
        od = f"{B}/mask/{a.ds}/{name}"
        os.makedirs(od, exist_ok=True)
        cmd = (f"#!/usr/bin/env bash\n# mask {a.ds} with {name}: generated by make_mask_jobs.py\nset -euo pipefail\n"
               f"export OMP_NUM_THREADS={T} RAYON_NUM_THREADS={T} MASKERAIDE_HOME={B}/tmp/maskeraide_home "
               f"TMPDIR={B}/tmp/mask_{a.ds}_{name}\nmkdir -p $TMPDIR $MASKERAIDE_HOME\ncd {od}\n"
               f"ln -sf {lib} lib.fa\nln -sf {g} {a.ds}.fa\n"
               f'echo "STEP rmfast start $(date +%s)"\n'
               f"{RMFAST} -pa {T} -q -no_is -norna -nolow -div 40 -cutoff 225 -lib lib.fa -dir {od} {a.ds}.fa\n"
               f'echo "STEP rmfast end $(date +%s)"\n')
        if a.force or not os.path.exists(f"{od}/cmd.sh"):
            with open(f"{od}/cmd.sh", "w") as f:
                f.write(cmd)
        rows.append(dict(job_id=f"mask__{a.ds}__{name}", ds=a.ds, tool=f"mask_{name}", threads=T, outdir=od,
                         size=os.path.getsize(g)))
    new = not os.path.exists(a.jobs)
    have = set()
    if not new:
        have = {r["job_id"] for r in csv.DictReader(open(a.jobs), delimiter="\t")}
    with open(a.jobs, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter="\t")
        if new:
            w.writeheader()
        for r in rows:
            if r["job_id"] not in have:
                w.writerow(r)
    print(f"make_mask_jobs: {len(rows)} jobs for {a.ds}", file=sys.stderr)


if __name__ == "__main__":
    main()

#!/usr/bin/env python
"""Write per-tool cmd.sh files and a jobs.tsv under the ltrkin_geno tree.

Wraps the main benchmark's make_jobs.tool_body() so tool commands and settings are
identical; only the per-dataset data dir, run dir and TMPDIR move under this tree.
"""
import sys

sys.dont_write_bytecode = True  # never write __pycache__ into the shared benchmark tree
import argparse
import csv
import os
from pathlib import Path

import lg_config as C

# Appended, not prepended: the main scripts dir has a queue.py that would shadow stdlib queue.
sys.path.append(str(C.BENCH / "scripts"))
import make_jobs  # noqa: E402

for _ds in ("camara_hap1", "camara_hap2"):  # C. amara: closest RefSeq relative is A. lyrata, never the target
    make_jobs.PROT.setdefault(_ds, C.PROT)

LG = C.LG
NT_VARS = ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS",
           "NUMBA_NUM_THREADS", "BLIS_NUM_THREADS", "RAYON_NUM_THREADS")


def job_script(ds, tool, root=LG):
    """Text of runs/<ds>/<tool>/cmd.sh, with data paths under `root`."""
    root = Path(root)
    rd = f"{root}/runs/{ds}/{tool}"
    nt = " ".join(f"{v}={make_jobs.T}" for v in NT_VARS)
    head = (f"#!/usr/bin/env bash\n# {ds} / {tool}: generated by make_tool_jobs.py\nset -euo pipefail\n"
            f"{make_jobs.CONDA}\nexport {nt}\nexport TMPDIR={root}/tmp/{ds}_{tool}\nmkdir -p $TMPDIR\ncd {rd}\n")
    body = make_jobs.tool_body(tool, ds, rd).replace(f"{C.BENCH}/data/{ds}", f"{root}/data/{ds}")
    return head + body


def write_jobs(dss, tools, out, root=LG, force=False):
    """Create run dirs, genome symlinks and cmd.sh; write jobs.tsv; return the rows."""
    root = Path(root)
    rows = []
    for ds in dss:
        g = root / "data" / ds / "genome.fa"
        if not g.exists():
            sys.exit(f"error: {g} missing (run prep_genome.py first)")
        for tool in tools:
            rd = root / "runs" / ds / tool
            rd.mkdir(parents=True, exist_ok=True)
            for suf in ("", ".fai"):
                link = rd / f"{ds}.fa{suf}"
                if not os.path.lexists(link):
                    os.symlink(f"{g}{suf}", link)
            path = rd / "cmd.sh"
            if force or not path.exists():
                path.write_text(job_script(ds, tool, root))
            rows.append(dict(job_id=f"{ds}__{tool}", ds=ds, tool=tool,
                             threads=make_jobs.USES.get(tool, make_jobs.T), outdir=str(rd), size=g.stat().st_size))
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["job_id", "ds", "tool", "threads", "outdir", "size"], delimiter="\t",
                           lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write runs/<ds>/<tool>/cmd.sh and a jobs.tsv under the ltrkin_geno tree.")
    ap.add_argument("--ds", nargs="+", required=True, help="datasets (data/<ds>/genome.fa under the tree)")
    ap.add_argument("--tools", nargs="+", default=C.TOOLS, choices=C.TOOLS, help="tools (default: all 9)")
    ap.add_argument("--out", required=True, help="jobs.tsv to write")
    ap.add_argument("--force", action="store_true", help="overwrite existing cmd.sh")
    ap.add_argument("-v", "--verbose", action="store_true", help="list each job written")
    a = ap.parse_args(argv)
    rows = write_jobs(a.ds, a.tools, a.out, force=a.force)
    if a.verbose:
        for r in rows:
            print(f"  {r['job_id']}\tthreads={r['threads']}", file=sys.stderr)
    print(f"make_tool_jobs: {len(rows)} jobs -> {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
